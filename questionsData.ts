// Helper function to normalize strings for comparison
export function normalizeAnswer(str: string): string {
  return str
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '') // remove diacritics
    .replace(/^(el|la|los|las|un|una|unos|unas|en|de|desde)\s+/i, '') // strip common Spanish articles/prepositions
    .replace(/[.,/#!$%^&*;:{}=\-_`~()?"'«»]/g, '')
    .trim();
}

export function isAnswerMatch(userInput: string, targetSpanish: string, targetArmenian: string): boolean {
  if (!userInput.trim()) return false;
  const userNorm = normalizeAnswer(userInput);
  const spNorm = normalizeAnswer(targetSpanish);
  const armNorm = userInput.trim().toLowerCase().replace(/[.,/#!$%^&*;:{}=\-_`~()?"'«»]/g, '');
  const targetArmNorm = targetArmenian.trim().toLowerCase().replace(/[.,/#!$%^&*;:{}=\-_`~()?"'«»]/g, '');

  if (userNorm === spNorm || userNorm === normalizeAnswer(targetSpanish)) return true;
  if (armNorm === targetArmNorm) return true;

  // Numeric checks (e.g. 11 for "once" or 90 for "noventa")
  if ((userNorm === '11' || userNorm === 'once') && spNorm.includes('once')) return true;
  if ((userNorm === '90' || userNorm === 'noventa') && spNorm.includes('noventa')) return true;

  return false;
}
